import React, { useState } from "react";
import {
  Sparkles,
  ArrowRight,
  RotateCcw,
  CheckCircle2,
  AlertTriangle,
  Lightbulb,
  Award,
  BookOpen,
} from "lucide-react";
import { Resume } from "../types/resume";
import { InterviewQuestion, InterviewAnswerEvaluation } from "../types/ats";
import { Translations } from "../i18n/translations";
import { safeInvoke } from "../utils/tauri";

interface InterviewSimulatorProps {
  resume: Resume;
  theme: "dark" | "light";
  language: string;
  t: Translations;
}

export const InterviewSimulator: React.FC<InterviewSimulatorProps> = ({
  resume,
  theme,
  t,
}) => {
  const isDark = theme === "dark";
  const i18n = t.interviewSim;

  const [targetRole, setTargetRole] = useState(
    resume.basics.label || "Lead AI Engineer"
  );
  const [interviewType, setInterviewType] = useState<
    "technical" | "behavioral" | "general" | "mixed"
  >("mixed");

  const [stage, setStage] = useState<
    "setup" | "generating" | "question" | "evaluating" | "feedback" | "summary"
  >("setup");
  const [questions, setQuestions] = useState<InterviewQuestion[]>([]);
  const [currentIndex, setCurrentIndex] = useState(0);
  const [candidateAnswer, setCandidateAnswer] = useState("");
  const [evaluations, setEvaluations] = useState<
    { question: InterviewQuestion; answer: string; eval: InterviewAnswerEvaluation }[]
  >([]);
  const [currentEval, setCurrentEval] = useState<InterviewAnswerEvaluation | null>(
    null
  );
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  const startInterview = async () => {
    setErrorMsg(null);
    setStage("generating");
    try {
      const qList = await safeInvoke<InterviewQuestion[]>(
        "generate_interview_questions",
        {
          profile: resume,
          targetRole,
          interviewType,
        }
      );
      if (!qList || qList.length === 0) {
        throw new Error("No questions were generated by the AI.");
      }
      setQuestions(qList);
      setCurrentIndex(0);
      setCandidateAnswer("");
      setCurrentEval(null);
      setEvaluations([]);
      setStage("question");
    } catch (err: unknown) {
      setErrorMsg(
        err instanceof Error ? err.message : String(err)
      );
      setStage("setup");
    }
  };

  const submitAnswer = async () => {
    if (!candidateAnswer.trim()) return;
    setErrorMsg(null);
    setStage("evaluating");
    const activeQ = questions[currentIndex];
    try {
      const evaluation = await safeInvoke<InterviewAnswerEvaluation>(
        "evaluate_interview_answer",
        {
          question: activeQ.question,
          candidateAnswer,
          profile: resume,
        }
      );
      setCurrentEval(evaluation);
      setEvaluations((prev) => [
        ...prev,
        { question: activeQ, answer: candidateAnswer, eval: evaluation },
      ]);
      setStage("feedback");
    } catch (err: unknown) {
      setErrorMsg(
        err instanceof Error ? err.message : String(err)
      );
      setStage("question");
    }
  };

  const nextQuestion = () => {
    if (currentIndex + 1 < questions.length) {
      setCurrentIndex((prev) => prev + 1);
      setCandidateAnswer("");
      setCurrentEval(null);
      setStage("question");
    } else {
      setStage("summary");
    }
  };

  const resetInterview = () => {
    setStage("setup");
    setQuestions([]);
    setCurrentIndex(0);
    setCandidateAnswer("");
    setCurrentEval(null);
    setEvaluations([]);
    setErrorMsg(null);
  };

  const averageScore =
    evaluations.length > 0
      ? Math.round(
          evaluations.reduce((acc, curr) => acc + curr.eval.score, 0) /
            evaluations.length
        )
      : 0;

  return (
    <div className="max-w-4xl mx-auto px-4 py-8">
      <div className="flex items-center justify-between mb-8 pb-4 border-b border-zinc-200 dark:border-zinc-800">
        <div>
          <h2 className="text-xl font-bold tracking-tight text-zinc-900 dark:text-white flex items-center gap-2">
            <Sparkles className="w-5 h-5 text-emerald-500" />
            {i18n?.title || "Simulateur d'Entretien"}
          </h2>
          <p className="text-xs text-zinc-500 dark:text-zinc-400 mt-1">
            {i18n?.subtitle || "Entraînez-vous aux entretiens ciblés avec évaluation pédagogique STAR et axes d'amélioration."}
          </p>
        </div>
        {stage !== "setup" && (
          <button
            onClick={resetInterview}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-medium border border-zinc-300 dark:border-zinc-700 hover:bg-zinc-100 dark:hover:bg-zinc-800 transition"
          >
            <RotateCcw className="w-3.5 h-3.5" />
            {i18n?.newSession || "Nouvelle session"}
          </button>
        )}
      </div>

      {errorMsg && (
        <div className="mb-6 p-4 rounded-xl border border-red-500/20 bg-red-500/10 text-red-600 dark:text-red-400 text-xs flex items-center gap-3">
          <AlertTriangle className="w-4 h-4 shrink-0" />
          <span>{errorMsg}</span>
        </div>
      )}

      {stage === "setup" && (
        <div
          className={`p-6 rounded-2xl border ${
            isDark ? "bg-zinc-900/60 border-zinc-800" : "bg-white border-zinc-200 shadow-sm"
          }`}
        >
          <div className="space-y-5">
            <div>
              <label className="block text-xs font-semibold uppercase tracking-wider text-zinc-500 dark:text-zinc-400 mb-2">
                {i18n?.targetRoleLabel || "Poste ou Métier ciblé"}
              </label>
              <input
                type="text"
                value={targetRole}
                onChange={(e) => setTargetRole(e.target.value)}
                placeholder={i18n?.targetRolePlaceholder || "Ex: Lead Développeur IA, Product Manager..."}
                className={`w-full px-4 py-2.5 rounded-xl border text-sm outline-none transition ${
                  isDark
                    ? "bg-zinc-950 border-zinc-800 text-white focus:border-emerald-500"
                    : "bg-zinc-50 border-zinc-200 text-zinc-900 focus:border-emerald-600"
                }`}
              />
            </div>

            <div>
              <label className="block text-xs font-semibold uppercase tracking-wider text-zinc-500 dark:text-zinc-400 mb-2">
                {i18n?.formatLabel || "Format d'entretien"}
              </label>
              <div className="grid grid-cols-2 md:grid-cols-4 gap-3">
                {[
                  { id: "mixed", label: i18n?.mixedLabel || "Mixte", desc: i18n?.mixedDesc || "Technique & comportemental" },
                  { id: "technical", label: i18n?.techLabel || "Technique", desc: i18n?.techDesc || "Architecture, code & stacks" },
                  { id: "behavioral", label: i18n?.behavLabel || "Comportemental", desc: i18n?.behavDesc || "Méthode STAR & soft skills" },
                  { id: "general", label: i18n?.generalLabel || "Général", desc: i18n?.generalDesc || "Motivation, parcours & vision" },
                ].map((type) => (
                  <button
                    key={type.id}
                    onClick={() => setInterviewType(type.id as typeof interviewType)}
                    className={`p-3.5 rounded-xl border text-left transition ${
                      interviewType === type.id
                        ? "border-emerald-500 bg-emerald-500/10 text-emerald-500"
                        : isDark
                        ? "border-zinc-800 hover:border-zinc-700 bg-zinc-950/40 text-zinc-400"
                        : "border-zinc-200 hover:border-zinc-300 bg-zinc-50 text-zinc-600"
                    }`}
                  >
                    <div className="font-semibold text-xs text-zinc-900 dark:text-white mb-0.5">
                      {type.label}
                    </div>
                    <div className="text-[11px] text-zinc-500 dark:text-zinc-400">
                      {type.desc}
                    </div>
                  </button>
                ))}
              </div>
            </div>

            <div className="pt-4 flex justify-end">
              <button
                onClick={startInterview}
                disabled={!targetRole.trim()}
                className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold transition disabled:opacity-50 shadow-sm"
              >
                <span>{i18n?.startBtn || "Démarrer l'entraînement"}</span>
                <ArrowRight className="w-4 h-4" />
              </button>
            </div>
          </div>
        </div>
      )}

      {stage === "generating" && (
        <div className="text-center py-16">
          <div className="inline-block animate-spin w-8 h-8 border-2 border-emerald-500 border-t-transparent rounded-full mb-4"></div>
          <p className="text-sm font-semibold text-zinc-800 dark:text-zinc-200">
            {i18n?.generatingTitle || "Génération des questions d'entretien sur-mesure..."}
          </p>
          <p className="text-xs text-zinc-500 mt-1">
            {i18n?.generatingDesc || "Analyse de votre CV et personnalisation des questions."}
          </p>
        </div>
      )}

      {stage === "question" && questions.length > 0 && (
        <div className="space-y-6">
          <div className="flex items-center justify-between text-xs font-medium text-zinc-500 dark:text-zinc-400">
            <span>
              {i18n?.questionOf?.replace("{current}", String(currentIndex + 1)).replace("{total}", String(questions.length)) || `Question ${currentIndex + 1} sur ${questions.length}`}
            </span>
            <span className="px-2.5 py-1 rounded-full bg-zinc-100 dark:bg-zinc-800 text-[11px]">
              {questions[currentIndex].category}
            </span>
          </div>

          <div className="w-full bg-zinc-200 dark:bg-zinc-800 h-1.5 rounded-full overflow-hidden">
            <div
              className="bg-emerald-500 h-full transition-all duration-300"
              style={{
                width: `${((currentIndex + 1) / questions.length) * 100}%`,
              }}
            ></div>
          </div>

          <div
            className={`p-6 rounded-2xl border ${
              isDark ? "bg-zinc-900/60 border-zinc-800" : "bg-white border-zinc-200 shadow-sm"
            }`}
          >
            <div className="mb-4">
              <div className="text-xs font-semibold text-emerald-500 uppercase tracking-wider mb-1">
                {i18n?.interviewerQuestion || "Question du recruteur"}
              </div>
              <h3 className="text-lg font-bold text-zinc-900 dark:text-white leading-relaxed">
                "{questions[currentIndex].question}"
              </h3>
              {questions[currentIndex].context && (
                <p className="text-xs text-zinc-500 dark:text-zinc-400 mt-2 italic">
                  {i18n?.contextLabel || "Contexte :"} {questions[currentIndex].context}
                </p>
              )}
            </div>

            <div className="mt-6">
              <label className="block text-xs font-semibold uppercase tracking-wider text-zinc-500 dark:text-zinc-400 mb-2">
                {i18n?.yourAnswerLabel || "Votre réponse orale ou rédigée"}
              </label>
              <textarea
                rows={6}
                value={candidateAnswer}
                onChange={(e) => setCandidateAnswer(e.target.value)}
                placeholder={i18n?.answerPlaceholder || "Formulez votre réponse avec la méthode STAR (Situation, Tâche, Action, Résultat)..."}
                className={`w-full p-4 rounded-xl border text-sm outline-none transition leading-relaxed ${
                  isDark
                    ? "bg-zinc-950 border-zinc-800 text-white focus:border-emerald-500"
                    : "bg-zinc-50 border-zinc-200 text-zinc-900 focus:border-emerald-600"
                }`}
              />
            </div>

            <div className="mt-4 flex justify-end">
              <button
                onClick={submitAnswer}
                disabled={!candidateAnswer.trim()}
                className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold transition disabled:opacity-50 shadow-sm"
              >
                <span>{i18n?.submitBtn || "Soumettre la réponse"}</span>
                <ArrowRight className="w-4 h-4" />
              </button>
            </div>
          </div>
        </div>
      )}

      {stage === "evaluating" && (
        <div className="text-center py-16">
          <div className="inline-block animate-spin w-8 h-8 border-2 border-emerald-500 border-t-transparent rounded-full mb-4"></div>
          <p className="text-sm font-semibold text-zinc-800 dark:text-zinc-200">
            {i18n?.evaluatingTitle || "Évaluation pédagogique en cours..."}
          </p>
          <p className="text-xs text-zinc-500 mt-1">
            {i18n?.evaluatingDesc || "Analyse de la clarté, de l'impact STAR et de la concordance avec votre profil."}
          </p>
        </div>
      )}

      {stage === "feedback" && currentEval && (
        <div className="space-y-6">
          <div
            className={`p-6 rounded-2xl border ${
              isDark ? "bg-zinc-900/60 border-zinc-800" : "bg-white border-zinc-200 shadow-sm"
            }`}
          >
            <div className="flex items-center justify-between pb-4 border-b border-zinc-200 dark:border-zinc-800">
              <div>
                <span className="text-xs uppercase font-semibold text-zinc-500 dark:text-zinc-400">
                  {i18n?.evalTitle || "Évaluation Question"} {currentIndex + 1}
                </span>
                <h3 className="text-sm font-bold text-zinc-900 dark:text-white mt-0.5">
                  "{questions[currentIndex].question}"
                </h3>
              </div>
              <div
                className={`px-4 py-2 rounded-xl text-center font-bold text-lg ${
                  currentEval.score >= 80
                    ? "bg-emerald-500/10 text-emerald-500 border border-emerald-500/20"
                    : currentEval.score >= 60
                    ? "bg-amber-500/10 text-amber-500 border border-amber-500/20"
                    : "bg-red-500/10 text-red-500 border border-red-500/20"
                }`}
              >
                {currentEval.score} / 100
              </div>
            </div>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-4 my-5">
              <div className="p-4 rounded-xl border border-emerald-500/20 bg-emerald-500/5">
                <div className="flex items-center gap-1.5 text-xs font-bold text-emerald-500 uppercase tracking-wider mb-2">
                  <CheckCircle2 className="w-3.5 h-3.5" />
                  {i18n?.strengthsTitle || "Points forts"}
                </div>
                <ul className="space-y-1.5 text-xs text-zinc-700 dark:text-zinc-300">
                  {currentEval.strengths.map((str, i) => (
                    <li key={i} className="flex items-start gap-1.5">
                      <span className="text-emerald-500 font-bold">•</span>
                      <span>{str}</span>
                    </li>
                  ))}
                </ul>
              </div>

              <div className="p-4 rounded-xl border border-amber-500/20 bg-amber-500/5">
                <div className="flex items-center gap-1.5 text-xs font-bold text-amber-500 uppercase tracking-wider mb-2">
                  <AlertTriangle className="w-3.5 h-3.5" />
                  {i18n?.improvementsTitle || "Axes d'amélioration"}
                </div>
                <ul className="space-y-1.5 text-xs text-zinc-700 dark:text-zinc-300">
                  {currentEval.improvements.map((imp, i) => (
                    <li key={i} className="flex items-start gap-1.5">
                      <span className="text-amber-500 font-bold">•</span>
                      <span>{imp}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </div>

            {currentEval.suggested_reformulation && (
              <div className="p-4 rounded-xl border border-zinc-200 dark:border-zinc-800 bg-zinc-50 dark:bg-zinc-950/60 mb-4">
                <div className="flex items-center gap-1.5 text-xs font-bold text-zinc-800 dark:text-zinc-200 uppercase tracking-wider mb-2">
                  <Lightbulb className="w-3.5 h-3.5 text-amber-500" />
                  {i18n?.starTitle || "Reformulation recommandée (Format STAR)"}
                </div>
                <p className="text-xs text-zinc-600 dark:text-zinc-300 leading-relaxed italic">
                  "{currentEval.suggested_reformulation}"
                </p>
              </div>
            )}

            {currentEval.pedagogy_notes && (
              <div className="p-3.5 rounded-xl bg-zinc-100 dark:bg-zinc-800/40 text-xs text-zinc-600 dark:text-zinc-400 flex items-start gap-2">
                <BookOpen className="w-4 h-4 shrink-0 text-emerald-500 mt-0.5" />
                <span>{currentEval.pedagogy_notes}</span>
              </div>
            )}

            <div className="mt-6 flex justify-end">
              <button
                onClick={nextQuestion}
                className="flex items-center gap-2 px-5 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold transition shadow-sm"
              >
                <span>
                  {currentIndex + 1 < questions.length
                    ? (i18n?.nextBtn || "Question suivante")
                    : (i18n?.finishBtn || "Voir le bilan final")}
                </span>
                <ArrowRight className="w-4 h-4" />
              </button>
            </div>
          </div>
        </div>
      )}

      {stage === "summary" && (
        <div className="space-y-6">
          <div
            className={`p-6 rounded-2xl border ${
              isDark ? "bg-zinc-900/60 border-zinc-800" : "bg-white border-zinc-200 shadow-sm"
            }`}
          >
            <div className="text-center py-6 border-b border-zinc-200 dark:border-zinc-800">
              <Award className="w-12 h-12 text-emerald-500 mx-auto mb-2" />
              <h3 className="text-xl font-bold text-zinc-900 dark:text-white">
                {i18n?.summaryTitle || "Bilan de l'Entretien"}
              </h3>
              <p className="text-xs text-zinc-500 dark:text-zinc-400 mt-1">
                {targetRole} ({interviewType})
              </p>
              <div className="inline-block mt-4 px-6 py-2.5 rounded-2xl bg-emerald-500/10 border border-emerald-500/20 text-emerald-500 font-extrabold text-2xl">
                {i18n?.overallScore || "Score Global :"} {averageScore} / 100
              </div>
            </div>

            <div className="divide-y divide-zinc-200 dark:divide-zinc-800 my-4">
              {evaluations.map((item, idx) => (
                <div key={idx} className="py-4">
                  <div className="flex items-center justify-between mb-1.5">
                    <span className="text-xs font-bold text-zinc-900 dark:text-white">
                      Q{idx + 1}. {item.question.question}
                    </span>
                    <span
                      className={`text-xs font-bold px-2.5 py-0.5 rounded-full ${
                        item.eval.score >= 80
                          ? "bg-emerald-500/10 text-emerald-500"
                          : item.eval.score >= 60
                          ? "bg-amber-500/10 text-amber-500"
                          : "bg-red-500/10 text-red-500"
                      }`}
                    >
                      {item.eval.score}/100
                    </span>
                  </div>
                  <p className="text-xs text-zinc-500 dark:text-zinc-400 line-clamp-2 italic mb-2">
                    "{item.answer}"
                  </p>
                  <p className="text-xs text-emerald-600 dark:text-emerald-400">
                    {item.eval.suggested_reformulation}
                  </p>
                </div>
              ))}
            </div>

            <div className="pt-4 flex justify-center">
              <button
                onClick={resetInterview}
                className="flex items-center gap-2 px-6 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold transition shadow-sm"
              >
                <RotateCcw className="w-4 h-4" />
                <span>{i18n?.restartBtn || "Recommencer un nouvel entraînement"}</span>
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
